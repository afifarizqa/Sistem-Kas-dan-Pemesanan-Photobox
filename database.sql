-- =====================================================
-- SISTEM AKUNTANSI KAS DAN PEMESANAN PHOTOBOX
-- =====================================================


-- =====================================================
-- BAGIAN 1
-- MENGHAPUS DATABASE LAMA
-- =====================================================

DROP TABLE IF EXISTS transaksi_kas CASCADE;
DROP TABLE IF EXISTS kas CASCADE;
DROP TABLE IF EXISTS pemesanan CASCADE;
DROP TABLE IF EXISTS pelanggan CASCADE;


-- =====================================================
-- BAGIAN 2
-- TABEL PELANGGAN
-- =====================================================

CREATE TABLE pelanggan (
    id_pelanggan BIGINT
        GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    nama VARCHAR(100)
        NOT NULL,

    no_hp VARCHAR(20)
        NOT NULL
);


-- =====================================================
-- BAGIAN 3
-- TABEL PEMESANAN
-- =====================================================

CREATE TABLE pemesanan (
    id_pemesanan BIGINT
        GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    id_pelanggan BIGINT
        NOT NULL,

    tanggal_pemesanan DATE
        NOT NULL
        DEFAULT CURRENT_DATE,

    tanggal_sesi DATE
        NOT NULL,

    jam_sesi TIME
        NOT NULL,

    jenis_paket VARCHAR(100)
        NOT NULL,

    total_harga NUMERIC(12,2)
        NOT NULL
        DEFAULT 0,

    status VARCHAR(30)
        NOT NULL
        DEFAULT 'Pending',

    CONSTRAINT fk_pemesanan_pelanggan
        FOREIGN KEY (id_pelanggan)
        REFERENCES pelanggan(id_pelanggan)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT cek_total_harga
        CHECK (total_harga >= 0),

    CONSTRAINT cek_status_pemesanan
        CHECK (
            status IN (
                'Pending',
                'Booked',
                'Selesai',
                'Batal'
            )
        )
);


-- =====================================================
-- BAGIAN 4
-- TABEL TRANSAKSI KAS
-- =====================================================

CREATE TABLE transaksi_kas (
    id_transaksi BIGINT
        GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    id_pemesanan BIGINT
        NOT NULL,

    tanggal DATE
        NOT NULL
        DEFAULT CURRENT_DATE,

    jenis VARCHAR(20)
        NOT NULL,

    jumlah NUMERIC(12,2)
        NOT NULL
        DEFAULT 0,

    keterangan TEXT,

    CONSTRAINT fk_transaksi_pemesanan
        FOREIGN KEY (id_pemesanan)
        REFERENCES pemesanan(id_pemesanan)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT cek_jenis_kas
        CHECK (
            jenis IN (
                'Pemasukan',
                'Pengeluaran'
            )
        ),

    CONSTRAINT cek_jumlah_kas
        CHECK (jumlah >= 0)
);


-- =====================================================
-- BAGIAN 5
-- AKSES CRUD UNTUK APLIKASI TANPA LOGIN
-- =====================================================

GRANT USAGE ON SCHEMA public TO anon;

GRANT SELECT, INSERT, UPDATE, DELETE
    ON TABLE public.pelanggan, public.pemesanan, public.transaksi_kas
    TO anon;

ALTER TABLE public.pelanggan ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.pemesanan ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.transaksi_kas ENABLE ROW LEVEL SECURITY;

CREATE POLICY pelanggan_anon_crud
    ON public.pelanggan
    FOR ALL
    TO anon
    USING (true)
    WITH CHECK (true);

CREATE POLICY pemesanan_anon_crud
    ON public.pemesanan
    FOR ALL
    TO anon
    USING (true)
    WITH CHECK (true);

CREATE POLICY transaksi_kas_anon_crud
    ON public.transaksi_kas
    FOR ALL
    TO anon
    USING (true)
    WITH CHECK (true);


